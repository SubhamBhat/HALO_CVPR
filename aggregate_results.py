"""
Aggregates multi-seed CSV outputs from `halo_experiments.py` into:
  1. Mean +/- std tables across seeds for Raw (tau=0), Calibrated (+tau*), and Temp-Scaled (+T*) stages.
  2. Paired two-sided t-tests against HALO [full] on matching seeds (Revision Plan #5).
  3. Quantitative ECE summary: win/loss counts, mean rank, and mean ECE before/after temperature scaling (Plan #7).
  4. Ready-to-paste LaTeX tables (`--latex_out`) separating training gains from post-hoc calibration gains.

Usage:
  python aggregate_results.py --csv results/runs.csv --latex_out results/revision_tables.tex
"""
import os
import csv
import math
import argparse
from collections import defaultdict
import numpy as np

try:
    from scipy.stats import ttest_rel
except ImportError:
    ttest_rel = None


def paired_pvalue(a, b):
    """Two-sided paired t-test p-value on matching seed arrays a and b."""
    a, b = np.asarray(a, dtype=np.float64), np.asarray(b, dtype=np.float64)
    n = len(a)
    if n < 2 or np.allclose(a, b):
        return 1.0
    if ttest_rel is not None:
        _, p = ttest_rel(a, b)
        return float(p) if not np.isnan(p) else 1.0
    diff = a - b
    sd = diff.std(ddof=1)
    if sd < 1e-12:
        return 1.0
    t_stat = abs(diff.mean()) / (sd / math.sqrt(n))
    # Normal tail approximation fallback
    return float(math.erfc(t_stat / math.sqrt(2.0)))


def load_runs(csv_path):
    """Returns dict[(dataset, backbone, method, variant, stage)][seed] -> metrics dict."""
    grouped = defaultdict(dict)
    with open(csv_path, newline="") as f:
        for r in csv.DictReader(f):
            key = (r["dataset"], r["backbone"], r["method"], r["variant"], r["stage"])
            seed = int(r["seed"])
            grouped[key][seed] = {
                "f1": float(r["f1"]),
                "acc": float(r["acc"]),
                "ece": float(r["ece"]),
                "head_f1": float(r.get("head_f1", 0.0) or 0.0),
                "med_f1": float(r.get("med_f1", 0.0) or 0.0),
                "tail_f1": float(r.get("tail_f1", 0.0) or 0.0),
                "tau": float(r.get("tau", 0.0) or 0.0),
            }
    return grouped


def fmt_ms(vals, scale=1.0, decimals=4):
    arr = np.asarray(vals, dtype=np.float64) * scale
    if len(arr) == 0:
        return "--"
    if len(arr) == 1:
        return f"{arr[0]:.{decimals}f}"
    return f"{arr.mean():.{decimals}f} +/- {arr.std(ddof=1):.{decimals}f}"


def fmt_tex(vals, bold=False, decimals=4):
    arr = np.asarray(vals, dtype=np.float64)
    if len(arr) == 0:
        return "---"
    s = f"{arr.mean():.{decimals}f}" if len(arr) == 1 else f"{arr.mean():.{decimals}f}$\\pm${arr.std(ddof=1):.{decimals}f}"
    return f"\\textbf{{{s}}}" if bold else s


def summarize(grouped, latex_path=None):
    configs = sorted({(k[0], k[1]) for k in grouped})
    tex_lines = [
        "% Auto-generated by aggregate_results.py",
        "% Separates raw (tau=0) and post-hoc calibrated (+tau*) metrics with multi-seed mean +/- std.",
    ]

    # Track global ECE statistics for Plan #7
    ece_tracker = defaultdict(lambda: {"raw": [], "tau": [], "temp_scale": [], "ranks_raw": [], "ranks_tau": []})

    for ds, bb in configs:
        print(f"\n{'=' * 116}")
        print(f"Dataset: {ds} | Backbone: {bb}")
        print(f"{'=' * 116}")
        header = (
            f"{'Method [Variant]':<34} | {'Raw F1 (tau=0)':<19} | {'+tau* F1':<19} | "
            f"{'Tail F1 (+tau*)':<19} | {'Raw ECE':<9} | {'+T* ECE':<9} | {'p vs HALO'}"
        )
        print(header)
        print("-" * 116)

        halo_raw_seeds = grouped.get((ds, bb, "HALO", "full", "raw"), {})
        halo_tau_seeds = grouped.get((ds, bb, "HALO", "full", "tau"), {})

        mv_pairs = sorted(
            {(k[2], k[3]) for k in grouped if k[0] == ds and k[1] == bb},
            key=lambda x: (x[0] == "HALO", x[0], x[1]),
        )

        # Compute ECE ranks among standard baselines + HALO [full]
        std_methods = [(m, v) for m, v in mv_pairs if v == "full"]
        for stage_name, rank_key in (("raw", "ranks_raw"), ("tau", "ranks_tau")):
            means = []
            for m, v in std_methods:
                sd = grouped.get((ds, bb, m, v, stage_name), {})
                if sd:
                    means.append((np.mean([x["ece"] for x in sd.values()]), m))
            means.sort(key=lambda t: t[0])
            for r_idx, (_, m) in enumerate(means, start=1):
                ece_tracker[m][rank_key].append(r_idx)

        tex_lines.append(f"\n% --- {ds} | {bb} ---")
        tex_lines.append("\\begin{tabular}{l|cc|c|cc|c}")
        tex_lines.append("\\toprule")
        tex_lines.append("Method & Raw F1 ($\\tau{=}0$) & $+\\tau^\\star$ F1 & Tail F1 ($+\\tau^\\star$) & Raw ECE & $+T^\\star$ ECE & $p$-val \\\\")
        tex_lines.append("\\midrule")

        best_raw = max(
            (np.mean([x["f1"] for x in grouped[(ds, bb, m, v, "raw")].values()])
             for m, v in mv_pairs if (ds, bb, m, v, "raw") in grouped),
            default=-1.0,
        )
        best_tau = max(
            (np.mean([x["f1"] for x in grouped[(ds, bb, m, v, "tau")].values()])
             for m, v in mv_pairs if (ds, bb, m, v, "tau") in grouped),
            default=-1.0,
        )

        for m, v in mv_pairs:
            raw_d = grouped.get((ds, bb, m, v, "raw"), {})
            tau_d = grouped.get((ds, bb, m, v, "tau"), {})
            tmp_d = grouped.get((ds, bb, m, v, "temp_scale"), {})

            raw_f1 = [raw_d[s]["f1"] for s in sorted(raw_d)]
            tau_f1 = [tau_d[s]["f1"] for s in sorted(tau_d)]
            tail_f1 = [tau_d[s]["tail_f1"] for s in sorted(tau_d)]
            raw_ece = [raw_d[s]["ece"] for s in sorted(raw_d)]
            tau_ece = [tau_d[s]["ece"] for s in sorted(tau_d)]
            tmp_ece = [tmp_d[s]["ece"] for s in sorted(tmp_d)]

            if v == "full":
                if raw_ece:
                    ece_tracker[m]["raw"].append(float(np.mean(raw_ece)))
                if tau_ece:
                    ece_tracker[m]["tau"].append(float(np.mean(tau_ece)))
                if tmp_ece:
                    ece_tracker[m]["temp_scale"].append(float(np.mean(tmp_ece)))

            common = sorted(set(tau_d) & set(halo_tau_seeds))
            if (m, v) == ("HALO", "full") or len(common) < 2:
                p_str, p_tex = "--", "---"
            else:
                pval = paired_pvalue([halo_tau_seeds[s]["f1"] for s in common], [tau_d[s]["f1"] for s in common])
                sig = "*" if pval < 0.05 else " (ns)"
                p_str = f"{pval:.4f}{sig}"
                p_tex = f"{pval:.3f}{'*' if pval < 0.05 else ''}"

            label = m if v == "full" else f"{m} [{v}]"
            r_ece_str = f"{np.mean(raw_ece):.4f}" if raw_ece else "--"
            t_ece_str = f"{np.mean(tmp_ece):.4f}" if tmp_ece else "--"
            print(
                f"{label:<34} | {fmt_ms(raw_f1):<19} | {fmt_ms(tau_f1):<19} | "
                f"{fmt_ms(tail_f1):<19} | {r_ece_str:<9} | {t_ece_str:<9} | {p_str}"
            )

            is_b_raw = bool(raw_f1 and abs(np.mean(raw_f1) - best_raw) < 1e-9)
            is_b_tau = bool(tau_f1 and abs(np.mean(tau_f1) - best_tau) < 1e-9)
            tex_label = label.replace("_", "\\_")
            tex_lines.append(
                f"{tex_label} & {fmt_tex(raw_f1, is_b_raw)} & {fmt_tex(tau_f1, is_b_tau)} & "
                f"{fmt_tex(tail_f1)} & {r_ece_str} & {t_ece_str} & {p_tex} \\\\"
            )

        tex_lines.append("\\bottomrule")
        tex_lines.append("\\end{tabular}")

    # Print Quantitative ECE Summary (Plan #7, Reviewer yQ6h)
    if ece_tracker:
        print(f"\n{'=' * 90}")
        print("QUANTITATIVE ECE SUMMARY ACROSS ALL RUN CONFIGURATIONS (Plan #7)")
        print(f"{'=' * 90}")
        print(f"{'Method':<18} | {'Mean Raw ECE':<14} | {'Mean +tau* ECE':<15} | {'Mean +T* ECE':<14} | {'Mean Rank (Raw / +tau*)'}")
        print("-" * 90)
        for m in sorted(ece_tracker):
            d = ece_tracker[m]
            mr = f"{np.mean(d['raw']):.4f}" if d["raw"] else "--"
            mt = f"{np.mean(d['tau']):.4f}" if d["tau"] else "--"
            mp = f"{np.mean(d['temp_scale']):.4f}" if d["temp_scale"] else "--"
            rr = f"{np.mean(d['ranks_raw']):.2f}" if d["ranks_raw"] else "--"
            rt = f"{np.mean(d['ranks_tau']):.2f}" if d["ranks_tau"] else "--"
            print(f"{m:<18} | {mr:<14} | {mt:<15} | {mp:<14} | {rr} / {rt}")

    if latex_path:
        os.makedirs(os.path.dirname(os.path.abspath(latex_path)), exist_ok=True)
        with open(latex_path, "w", encoding="utf-8") as f:
            f.write("\n".join(tex_lines) + "\n")
        print(f"\nSaved LaTeX tables to {latex_path}")


def main():
    ap = argparse.ArgumentParser(description="Aggregate multi-seed HALO experiment runs")
    ap.add_argument("--csv", default="results/runs.csv", help="Path to runs.csv")
    ap.add_argument("--latex_out", default=None, help="Optional path to write LaTeX tables")
    args = ap.parse_args()
    if not os.path.exists(args.csv):
        raise SystemExit(f"CSV file not found: {args.csv}")
    grouped = load_runs(args.csv)
    summarize(grouped, args.latex_out)


if __name__ == "__main__":
    main()
